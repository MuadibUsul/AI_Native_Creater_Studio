/**
 * 纯 TypeScript 的 SHA-256 与规范 JSON（V5-M4 RenderPlan `planHash`）。
 *
 * 内核需要在服务端、浏览器与 Worker 中给出**同一个**哈希，且不得导入 `node:*`（arch-check R10），
 * 因此不用 `node:crypto` / WebCrypto（后者是异步 API，且依赖宿主环境）。
 * 输入规模是一份序列的计划（KB 级），纯实现的开销可忽略。
 */

